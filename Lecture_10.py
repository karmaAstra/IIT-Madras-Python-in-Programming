#Arthmatic Operations are:
# + , - , * , / , // , % , **

a = 2
b = 3 
print("Addition:", a + b) # 5
print("Subtraction:", a - b) # -1
print("Multiplication:", a * b) # 6
print("Division:", a / b) # 0.6666666666666666
print("Floor Division:", a // b) # 0
print("Modulus:", a % b) # 2
print("Exponentiation:", a ** b) # 8


# Relational Operators are:
# < , > , <= , >= , == , !=
print("Less than:", a < b) # True
print("Greater than:", a > b) # False
print("Less than or equal to:", a <= b) # True
print("Greater than or equal to:", a >= b) # False
print("Equal to:", a == b) # False
print("Not equal to:", a != b) # True



#Logical Operators are:
# and , or , not
print(True and True) # True
print(True and False) # False
print(False or True) # True
print(False or False) # False
print(not True) # False
print(not False) # True