# Escape characters are the special methods used to use spacial things

print('it\'s a beautiful day') # \' --> used a single character as '
print("We are from \"IIT Madras\"") # Allows to use \"
print("My name is Dinesh. \t I am from Jharkhand") # \t --> Gives a tab space
print("My name is Dinesh. \n I am from Jharkhand") # \n --> Adds to a new line



